export interface V6CleanupOptions {
    /** Package templates directory (what this release ships). */
    templatesDir: string;
    /** Skills this release installs into .claude/skills/. */
    shippedSkills: readonly string[];
    /** Renders a shipped agent template for this project (placeholder substitution). */
    renderAgent: (template: string) => string;
}

export interface V6CleanupPlan {
    /** Rulebook-owned leftovers (files/dirs) to move into `.rulebook/backup/<timestamp>/`. Repo-relative. */
    remove: string[];
    /** Files at rulebook paths whose content was edited — kept, reported as "edited, kept". */
    preserved: string[];
    /** Uppercase spec files to rename to the v7 lowercase convention. */
    rename: Array<{ from: string; to: string }>;
    /** Unedited agents/skills rulebook still ships, rewritten with the current version. */
    refresh: Array<{ path: string; content: string }>;
}

async function exists(p: string): Promise<boolean> {
    return fs.stat(p).then(
        () => true,
        () => false
    );
}

async function readText(p: string): Promise<string | null> {
    try {
        return await fs.readFile(p, 'utf-8');
    } catch {
        return null;
    }
}

async function listFiles(dir: string, ext?: string): Promise<string[]> {
    try {
        const entries = await fs.readdir(dir, { withFileTypes: true });
        return entries
            .filter((e) => e.isFile() && (!ext || e.name.endsWith(ext)))
            .map((e) => e.name);
    } catch {
        return [];
    }
}

async function listDirs(dir: string): Promise<string[]> {
    try {
        const entries = await fs.readdir(dir, { withFileTypes: true });
        return entries.filter((e) => e.isDirectory()).map((e) => e.name);
    } catch {
        return [];
    }
}

/** Compute the cleanup plan. Read-only. */
export async function planV6Cleanup(
    projectRoot: string,
    options?: V6CleanupOptions
): Promise<V6CleanupPlan> {
    const plan: V6CleanupPlan = { remove: [], preserved: [], rename: [], refresh: [] };
    const abs = (rel: string) => path.join(projectRoot, rel);

    /** Retired path: unedited (catalogue hash or owned marker) → backup, else edited → kept. */
    const retire = async (rel: string, alsoOwned?: (content: string) => boolean) => {
        const content = await readText(abs(rel));
        if (content === null) return;
        if (isCatalogued(rel, content) || alsoOwned?.(content)) plan.remove.push(rel);
        else plan.preserved.push(rel);
    };

    /** Shipped path: unchanged → nothing; unedited old version → refresh; edited → kept. */
    const refresh = async (rel: string, current: string) => {
        const content = await readText(abs(rel));
        if (content === null) return;
        if (normalizeContent(content) === normalizeContent(current)) return;
        if (isCatalogued(rel, content)) plan.refresh.push({ path: rel, content: current });
        else plan.preserved.push(rel);
    };

    const shipped = options ? await readShipped(options.templatesDir) : null;

    // .claude/rules — retired names (catalogue or legacy marker), plus any
    // other catalogued path this release no longer generates.
    for (const file of await listFiles(abs('.claude/rules'), '.md')) {
        const rel = `.claude/rules/${file}`;
        const base = file.replace(/\.md$/, '');
        if (RETIRED_CLAUDE_RULES.includes(base)) {
            await retire(rel, (c) => OWNED_MARKERS.some((m) => c.includes(m)));
        } else if (shipped && !shipped.rules.has(file) && isCataloguedPath(rel)) {
            await retire(rel);
        }
    }

    // .claude/agents — shipped ones refresh, retired catalogued ones go.
    if (shipped && options) {
        for (const file of await listFiles(abs('.claude/agents'), '.md')) {
            const rel = `.claude/agents/${file}`;
            const template = shipped.agents.get(file);
            if (template !== undefined) await refresh(rel, options.renderAgent(template));
            else if (isCataloguedPath(rel)) await retire(rel);
        }
    }

    // .claude/hooks — retired scripts are always rulebook-owned; other
    // catalogued scripts this release no longer ships go by content.
    for (const file of await listFiles(abs('.claude/hooks'))) {
        const rel = `.claude/hooks/${file}`;
        if (RETIRED_HOOK_SCRIPTS.includes(file)) plan.remove.push(rel);
        else if (shipped && !CURRENT_HOOK_SCRIPTS.includes(file) && isCataloguedPath(rel)) {
            await retire(rel);
        }
    }

    // .claude/skills — retired-subsystem skills always go; shipped skills
    // refresh; other catalogued skills go when unedited (SKILL.md alone).
    for (const name of await listDirs(abs('.claude/skills'))) {
        const dirRel = `.claude/skills/${name}`;
        if (RETIRED_SKILLS.includes(name)) {
            plan.remove.push(dirRel);
            continue;
        }
        if (!shipped || !options) continue;
        const files = await listFiles(abs(dirRel));
        const skillFile = files.find((f) => f.toLowerCase() === 'skill.md');
        if (!skillFile) continue;
        const rel = `${dirRel}/${skillFile}`;
        const current = options.shippedSkills.includes(name) ? shipped.skills.get(name) : undefined;
        if (current !== undefined) {
            await refresh(rel, current);
        } else if (isCataloguedPath(rel)) {
            const content = (await readText(abs(rel))) ?? '';
            const subdirs = await listDirs(abs(dirRel));
            const alone = files.length === 1 && subdirs.length === 0;
            if (alone && isCatalogued(rel, content)) plan.remove.push(dirRel);
            else plan.preserved.push(rel);
        }
    }

    // .claude/commands — phase6-retired names (marker or catalogue), plus
    // any other catalogued command this release no longer ships.
    for (const file of await listFiles(abs('.claude/commands'), '.md')) {
        const rel = `.claude/commands/${file}`;
        if (RETIRED_COMMANDS.includes(file)) {
            await retire(rel, (c) => COMMAND_MARKERS.some((m) => c.includes(m)));
        } else if (shipped && !shipped.commands.has(file) && isCataloguedPath(rel)) {
            await retire(rel);
        }
    }

    // .rulebook/specs — retired docs, catalogued specs this release no longer
    // generates (e.g. quality_enforcement.md, tier1_prohibitions.md), then
    // uppercase → lowercase normalization for the rest.
    const specsDir = abs('.rulebook/specs');
    if (await exists(specsDir)) {
        const retired = new Set(RETIRED_SPECS);
        for (const entry of await listFiles(specsDir)) {
            const rel = `.rulebook/specs/${entry}`;
            if (retired.has(entry)) {
                plan.remove.push(rel);
                continue;
            }
            const lower = entry.toLowerCase();
            if (shipped && !shipped.specs.has(lower) && isCataloguedPath(rel)) {
                await retire(rel);
                continue;
            }
            if (entry !== lower && entry.endsWith('.md')) {
                plan.rename.push({ from: rel, to: `.rulebook/specs/${lower}` });
            }
        }
    }

    // .rulebook/rules — the v5/v6 canonical source dir is fully retired:
    // retired names always go, other verbatim template copies go by content.
    for (const entry of await listFiles(abs('.rulebook/rules'))) {
        const rel = `.rulebook/rules/${entry}`;
        const base = entry.replace(/\.md$/, '');
        if (RETIRED_CLAUDE_RULES.includes(base)) {
            plan.remove.push(rel);
        } else if (isCataloguedPath(rel)) {
            const content = await readText(abs(rel));
            if (content !== null && isCatalogued(rel, content)) plan.remove.push(rel);
        }
    }

    // Loose retired .rulebook files + the handoff directory.
    for (const name of RETIRED_RULEBOOK_FILES) {
        const rel = `.rulebook/${name}`;
        if (await exists(abs(rel))) plan.remove.push(rel);
    }
    if (await exists(abs('.rulebook/handoff'))) plan.remove.push('.rulebook/handoff');

    return plan;
}

interface ShippedAssets {
    /** .claude/rules file names this release can generate. */
    rules: Set<string>;
    /** Agent file name → template. */
    agents: Map<string, string>;
    /** Dev skill name → SKILL.md template. */
    skills: Map<string, string>;
    /** .claude/commands file names. */
    commands: Set<string>;
    /** Lowercase .rulebook/specs file names this release generates. */
    specs: Set<string>;
}

async function readShipped(templatesDir: string): Promise<ShippedAssets> {
    const rules = new Set<string>(GENERATED_RULES);
    for (const f of await listFiles(path.join(templatesDir, 'rules'), '.md')) rules.add(f);

    const agents = new Map<string, string>();
    for (const f of await listFiles(path.join(templatesDir, 'agents'), '.md')) {
        const t = await readText(path.join(templatesDir, 'agents', f));
        if (t !== null) agents.set(f, t);
    }

    const skills = new Map<string, string>();
    const devDir = path.join(templatesDir, 'skills', 'dev');
    for (const name of await listDirs(devDir)) {
        const t = await readText(path.join(devDir, name, 'SKILL.md'));
        if (t !== null) skills.set(name, t);
    }

    const commands = new Set(await listFiles(path.join(templatesDir, 'commands'), '.md'));

    const specs = new Set<string>(['git.md']);
    for (const f of await listFiles(path.join(templatesDir, 'core'), '.md')) {
        specs.add(f.toLowerCase());
    }

    return { rules, agents, skills, commands, specs };
}

export interface V6CleanupResult {
    /** Paths moved into the backup directory. */
    removed: string[];
    /** `from → to` spec renames. */
    renamed: string[];
    /** Agents/skills rewritten with the current version. */
    refreshed: string[];
    /** Repo-relative backup directory, or null when nothing was moved. */
    backupDir: string | null;
}

/** Move a file or directory, falling back to copy + remove across devices. */
async function move(src: string, dst: string): Promise<void> {
    await fs.mkdir(path.dirname(dst), { recursive: true });
    try {
        await fs.rename(src, dst);
    } catch {
        await fs.cp(src, dst, { recursive: true });
        await fs.rm(src, { recursive: true, force: true });
    }
}

/**
 * Apply a cleanup plan: leftovers move to `.rulebook/backup/<timestamp>/<path>`,
 * specs are renamed, shipped agents/skills refreshed. Returns what happened.
 */
export async function applyV6Cleanup(
    projectRoot: string,
    plan: V6CleanupPlan,
    now: Date = new Date()
): Promise<V6CleanupResult> {
    const removed: string[] = [];
    const renamed: string[] = [];
    const refreshed: string[] = [];
    const backupRel = `.rulebook/backup/${now.toISOString().replace(/[:.]/g, '-')}`;

    for (const relPath of plan.remove) {
        try {
            await move(path.join(projectRoot, relPath), path.join(projectRoot, backupRel, relPath));
            removed.push(relPath);
        } catch {
            // best-effort — report only what actually moved
        }
    }

    for (const { from, to } of plan.rename) {
        const src = path.join(projectRoot, from);
        const dst = path.join(projectRoot, to);
        try {
            // Two-step rename survives case-insensitive filesystems.
            const tmp = `${dst}.v7tmp`;
            await fs.rename(src, tmp);
            await fs.rename(tmp, dst);
            renamed.push(`${from} → ${to}`);
        } catch {
            // best-effort
        }
    }

    for (const { path: relPath, content } of plan.refresh) {
        try {
            await fs.writeFile(path.join(projectRoot, relPath), content, 'utf-8');
            refreshed.push(relPath);
        } catch {
            // best-effort
        }
    }

    // Drop .rulebook/rules if the cleanup emptied it.
    const canonicalDir = path.join(projectRoot, '.rulebook', 'rules');
    try {
        const left = await fs.readdir(canonicalDir);
        if (left.length === 0) await fs.rmdir(canonicalDir);
    } catch {
        // absent — fine
    }

    return { removed, renamed, refreshed, backupDir: removed.length > 0 ? backupRel : null };
}
