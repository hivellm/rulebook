/**
 * phase1_update-cleanup (F-030, F-041, F-042): the legacy catalogue tells
 * unedited v5/v6 output from user edits; `update` moves the former to
 * .rulebook/backup/, keeps and reports the latter, refreshes shipped
 * agents/skills, and strips retired or broken rulebook hooks on every event.
 *
 * Fixtures under tests/fixtures/legacy/ are real installed files from
 * upgraded projects (Synap, this repo), not hand-written approximations.
 */

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FIXTURES = path.join(ROOT, 'tests', 'fixtures', 'legacy');
const fixture = (name: string) => readFileSync(path.join(FIXTURES, name), 'utf-8');
const NOW = new Date('2026-10-14T12:00:00.000Z');
const BACKUP = '.rulebook/backup/2026-10-14T12-00-00-000Z';

function cleanupOptions(language?: string): V6CleanupOptions {
    const placeholders = resolveAgentPlaceholders(language);
    return {
        templatesDir: getTemplatesDir(),
        shippedSkills: DEFAULT_DEV_SKILLS,
        renderAgent: (t) => substituteAgentPlaceholders(t, placeholders),
    };
}

describe('legacy catalogue', () => {
    it('recognises a v6-projected rule (no "Generated by" marker) at its path', () => {
        const content = fixture('no-shortcuts.v6-projected.md');
        expect(content).not.toContain('Generated by');
        expect(content.startsWith('# ')).toBe(true);
        expect(isCatalogued('.claude/rules/no-shortcuts.md', content)).toBe(true);
    });

    it('ignores CRLF and trailing whitespace when hashing', () => {
        const content = fixture('no-shortcuts.v6-projected.md');
        const crlf = content.replace(/\r?\n/g, '  \r\n') + '\r\n\r\n';
        expect(normalizeContent(crlf)).toBe(normalizeContent(content));
        expect(isCatalogued('.claude/rules/no-shortcuts.md', crlf)).toBe(true);
    });

    it('rejects edited content and content at a different path', () => {
        const content = fixture('no-shortcuts.v6-projected.md');
        expect(isCatalogued('.claude/rules/no-shortcuts.md', content + '\nmy note\n')).toBe(false);
        expect(isCatalogued('.claude/rules/git-safety.md', content)).toBe(false);
        expect(isCataloguedPath('.claude/rules/my-own-rule.md')).toBe(false);
    });

    it('looks spec names up case-insensitively (v7 lowercased them)', () => {
        const content = fixture('quality_enforcement.v6.md');
        expect(isCatalogued('.rulebook/specs/quality_enforcement.md', content)).toBe(true);
        expect(isCatalogued('.rulebook/specs/QUALITY_ENFORCEMENT.md', content)).toBe(true);
    });

    it('knows the rust-substituted v7.4 implementer agent', () => {
        expect(
            isCatalogued('.claude/agents/implementer.md', fixture('implementer.v7.4-rust.md'))
        ).toBe(true);
    });
});

describe('agent language substitution (F-041)', () => {
    it('writes the language proper name, keeping the id-keyed defaults', () => {
        expect(resolveAgentPlaceholders('typescript')).toMatchObject({
            '{{language}}': 'TypeScript',
            '{{test_framework}}': 'vitest',
            '{{file_naming}}': 'kebab-case',
        });
        expect(resolveAgentPlaceholders('rust')['{{language}}']).toBe('Rust');
        expect(resolveAgentPlaceholders('csharp')['{{language}}']).toBe('C#');
        expect(resolveAgentPlaceholders(undefined)['{{language}}']).toBe('TypeScript');
        expect(resolveAgentPlaceholders('nim')['{{language}}']).toBe('nim');
    });

    it('shipped agent templates carry no maxTurns cap (F-043)', () => {
        const dir = path.join(getTemplatesDir(), 'agents');
        for (const file of readdirSync(dir).filter((f) => f.endsWith('.md'))) {
            const text = readFileSync(path.join(dir, file), 'utf-8');
            const frontmatter = text.match(/^---\r?\n([\s\S]*?)\r?\n---/)?.[1] ?? '';
            expect(frontmatter, file).not.toMatch(/^maxTurns:/m);
            expect(frontmatter, file).toMatch(/^name:/m);
            expect(frontmatter, file).toMatch(/^description:/m);
            expect(frontmatter, file).toMatch(/^model:/m);
            expect(frontmatter, file).toMatch(/^tools:/m);
        }
    });
});

describe('update legacy cleanup', () => {
    let root: string;
    const write = async (rel: string, content: string) => {
        const p = path.join(root, rel);
        await fs.mkdir(path.dirname(p), { recursive: true });
        await fs.writeFile(p, content);
    };
    const exists = (rel: string) =>
        fs.stat(path.join(root, rel)).then(
            () => true,
            () => false
        );
    const read = (rel: string) => fs.readFile(path.join(root, rel), 'utf-8');

    beforeEach(async () => {
        root = await fs.mkdtemp(path.join(os.tmpdir(), 'rb-legacy-cleanup-'));
    });

    afterEach(async () => {
        await fs.rm(root, { recursive: true, force: true });
    });

    it('moves an unedited v6-projected rule to .rulebook/backup/<timestamp>/ with its path', async () => {
        const content = fixture('no-shortcuts.v6-projected.md');
        await write('.claude/rules/no-shortcuts.md', content);

        const plan = await planV6Cleanup(root, cleanupOptions('typescript'));
        expect(plan.remove).toEqual(['.claude/rules/no-shortcuts.md']);
        expect(plan.preserved).toEqual([]);

        const result = await applyV6Cleanup(root, plan, NOW);
        expect(result.removed).toEqual(['.claude/rules/no-shortcuts.md']);
        expect(result.backupDir).toBe(BACKUP);
        expect(await exists('.claude/rules/no-shortcuts.md')).toBe(false);
        expect(await read(`${BACKUP}/.claude/rules/no-shortcuts.md`)).toBe(content);
    });

    it('keeps an edited file at a retired path and reports it as edited', async () => {
        const edited = fixture('no-shortcuts.v6-projected.md') + '\n## Our team addendum\n';
        await write('.claude/rules/no-shortcuts.md', edited);
        await write(
            '.rulebook/specs/tier1_prohibitions.md',
            '<!-- TIER1_PROHIBITIONS:START -->\n# our own version\n<!-- TIER1_PROHIBITIONS:END -->'
        );

        const plan = await planV6Cleanup(root, cleanupOptions('typescript'));
        expect(plan.remove).toEqual([]);
        expect(plan.preserved).toEqual([
            '.claude/rules/no-shortcuts.md',
            '.rulebook/specs/tier1_prohibitions.md',
        ]);

        const result = await applyV6Cleanup(root, plan, NOW);
        expect(result.backupDir).toBeNull();
        expect(await read('.claude/rules/no-shortcuts.md')).toBe(edited);
    });

    it('moves lowercase and uppercase legacy specs instead of renaming them', async () => {
        const spec = fixture('quality_enforcement.v6.md');
        await write('.rulebook/specs/quality_enforcement.md', spec);
        await write('.rulebook/specs/TIER1_PROHIBITIONS.md', 'user notes');
        await write('.rulebook/specs/TYPESCRIPT.md', '# ts spec');

        const plan = await planV6Cleanup(root, cleanupOptions('typescript'));
        expect(plan.remove).toEqual(['.rulebook/specs/quality_enforcement.md']);
        expect(plan.preserved).toEqual(['.rulebook/specs/TIER1_PROHIBITIONS.md']);
        expect(plan.rename).toEqual([
            { from: '.rulebook/specs/TYPESCRIPT.md', to: '.rulebook/specs/typescript.md' },
        ]);

        await applyV6Cleanup(root, plan, NOW);
        expect(await read(`${BACKUP}/.rulebook/specs/quality_enforcement.md`)).toBe(spec);
    });

    it('moves retired v5/v6 agents, skills and commands; leaves user ones alone', async () => {
        await write(
            '.claude/agents/i18n-engineer.md',
            fixture('implementer.v7.4-rust.md').replace('implementer', 'i18n-engineer')
        );
        await write('.claude/skills/debug/SKILL.md', fixture('debug-skill.v6.md'));
        await write(
            '.claude/commands/rulebook-memory-save.md',
            fixture('rulebook-memory-save.v5.md')
        );
        await write('.claude/agents/shader-engineer.md', '---\nname: shader-engineer\n---\nmine');
        await write('.claude/skills/my-skill/SKILL.md', '---\nname: my-skill\n---\nmine');

        const plan = await planV6Cleanup(root, cleanupOptions('typescript'));
        // i18n-engineer content is not any shipped version of that agent → edited, kept.
        expect(plan.preserved).toEqual(['.claude/agents/i18n-engineer.md']);
        expect(plan.remove.sort()).toEqual(
            ['.claude/commands/rulebook-memory-save.md', '.claude/skills/debug'].sort()
        );

        await applyV6Cleanup(root, plan, NOW);
        expect(await exists('.claude/skills/debug')).toBe(false);
        expect(await exists(`${BACKUP}/.claude/skills/debug/SKILL.md`)).toBe(true);
        expect(await exists('.claude/agents/shader-engineer.md')).toBe(true);
        expect(await exists('.claude/skills/my-skill/SKILL.md')).toBe(true);
    });

    it('refreshes an unedited shipped agent with the project language and no maxTurns', async () => {
        await write('.claude/agents/implementer.md', fixture('implementer.v7.4-rust.md'));

        const plan = await planV6Cleanup(root, cleanupOptions('typescript'));
        expect(plan.refresh.map((r) => r.path)).toEqual(['.claude/agents/implementer.md']);
        await applyV6Cleanup(root, plan, NOW);

        const refreshed = await read('.claude/agents/implementer.md');
        expect(refreshed).toContain('Writes production-quality TypeScript code');
        expect(refreshed).not.toMatch(/\brust\b/i);
        expect(refreshed).not.toContain('maxTurns');
    });

    it('keeps and reports an edited shipped agent or skill', async () => {
        const agent = fixture('implementer.v7.4-rust.md') + '\nAlways run `cargo deny`.\n';
        await write('.claude/agents/implementer.md', agent);
        await write('.claude/skills/analysis/SKILL.md', '---\nname: analysis\n---\nmy version');

        const plan = await planV6Cleanup(root, cleanupOptions('rust'));
        expect(plan.refresh).toEqual([]);
        expect(plan.preserved.sort()).toEqual(
            ['.claude/agents/implementer.md', '.claude/skills/analysis/SKILL.md'].sort()
        );

        // The skills installer honours the edit too.
        const installed = await installDevSkills(root, getTemplatesDir());
        expect(installed).not.toContain('analysis');
        expect(await read('.claude/skills/analysis/SKILL.md')).toContain('my version');
    });

    it('is idempotent: a second plan after applying has nothing to move or refresh', async () => {
        await write('.claude/rules/no-shortcuts.md', fixture('no-shortcuts.v6-projected.md'));
        await write('.claude/agents/implementer.md', fixture('implementer.v7.4-rust.md'));
        await write('.claude/skills/debug/SKILL.md', fixture('debug-skill.v6.md'));
        await write('.rulebook/specs/quality_enforcement.md', fixture('quality_enforcement.v6.md'));
        await write('.claude/hooks/enforce-pre-tool.sh', '#!/bin/sh\n');

        const first = await planV6Cleanup(root, cleanupOptions('typescript'));
        expect(first.remove.length).toBe(4);
        expect(first.refresh.length).toBe(1);
        await applyV6Cleanup(root, first, NOW);

        const second = await planV6Cleanup(root, cleanupOptions('typescript'));
        expect(second).toEqual({ remove: [], preserved: [], rename: [], refresh: [] });
    });
});

describe('hook cleanup on every event and settings.local.json (F-042)', () => {
    let root: string;
    const settingsWith = async (file: string, hooks: Record<string, unknown>) => {
        await fs.mkdir(path.dirname(file), { recursive: true });
        await fs.writeFile(file, JSON.stringify({ hooks }, null, 2));
    };
    const cmd = (command: string) => ({ hooks: [{ type: 'command', command }] });
    const commands = async (file: string) => {
        const json = JSON.parse(await fs.readFile(file, 'utf-8'));
        const out: string[] = [];
        for (const [event, list] of Object.entries(json.hooks ?? {})) {
            for (const entry of list as Array<{ hooks: Array<{ command: string }> }>) {
                for (const h of entry.hooks) out.push(`${event}: ${h.command}`);
            }
        }
        return out;
    };

    beforeEach(async () => {
        root = await fs.mkdtemp(path.join(os.tmpdir(), 'rb-hook-cleanup-'));
    });

    afterEach(async () => {
        await fs.rm(root, { recursive: true, force: true });
    });

    it('strips retired rulebook hooks on any event and keeps user hooks there', async () => {
        await settingsWith(getClaudeSettingsPath(root), {
            PostToolUse: [cmd('bash .claude/hooks/enforce-no-deferred.sh'), cmd('npm run lint')],
            PreCompact: [cmd('bash .claude/hooks/on-compact-reinject.sh')],
            SubagentStop: [
                cmd('bash "$CLAUDE_PROJECT_DIR/.claude/hooks/enforce-mcp-for-tasks.sh"'),
            ],
            SessionEnd: [cmd('powershell -File .claude/hooks/terse-mode-tracker.ps1')],
            Notification: [cmd('bash .claude/hooks/my-update-check.sh')],
        });

        const result = await applyClaudeSettings(root, {});
        const after = await commands(getClaudeSettingsPath(root));
        expect(after).toEqual([
            'PostToolUse: npm run lint',
            'Notification: bash .claude/hooks/my-update-check.sh',
        ]);
        expect(result.removedHooks).toEqual([
            'settings.json PostToolUse: bash .claude/hooks/enforce-no-deferred.sh',
            'settings.json PreCompact: bash .claude/hooks/on-compact-reinject.sh',
            'settings.json SubagentStop: bash "$CLAUDE_PROJECT_DIR/.claude/hooks/enforce-mcp-for-tasks.sh"',
            'settings.json SessionEnd: powershell -File .claude/hooks/terse-mode-tracker.ps1',
        ]);
    });

    it('drops an undesired rulebook entry; never a user entry whose script is missing', async () => {
        await settingsWith(getClaudeSettingsPath(root), {
            UserPromptSubmit: [cmd('bash $CLAUDE_PROJECT_DIR/.claude/hooks/jev-gate.sh prompt')],
            Stop: [cmd('bash .claude/hooks/my-missing-hook.sh')],
        });

        // Prompt gate not desired → its (scriptless) entry goes; the user's stays.
        const result = await applyClaudeSettings(root, {});
        expect(await commands(getClaudeSettingsPath(root))).toEqual([
            'Stop: bash .claude/hooks/my-missing-hook.sh',
        ]);
        expect(result.removedHooks).toEqual([
            'settings.json UserPromptSubmit: bash $CLAUDE_PROJECT_DIR/.claude/hooks/jev-gate.sh prompt',
        ]);
    });

    it('cleans settings.local.json: retired names and missing scripts go, working entries stay', async () => {
        await fs.mkdir(path.join(root, '.claude', 'hooks'), { recursive: true });
        await fs.writeFile(
            path.join(root, '.claude', 'hooks', 'no-os-scheduling.sh'),
            '#!/bin/sh\n'
        );
        await settingsWith(getClaudeLocalSettingsPath(root), {
            PreToolUse: [
                cmd('bash .claude/hooks/enforce-pre-tool.sh'),
                cmd('bash $CLAUDE_PROJECT_DIR/.claude/hooks/no-os-scheduling.sh'),
                cmd('bash $CLAUDE_PROJECT_DIR/.claude/hooks/protect-task-scaffolding.sh'),
                cmd('./scripts/my-guard.sh'),
            ],
            SessionStart: [cmd('bash .claude/hooks/resume-from-handoff.sh')],
        });

        const result = await applyClaudeSettings(root, {});
        expect(await commands(getClaudeLocalSettingsPath(root))).toEqual([
            'PreToolUse: bash $CLAUDE_PROJECT_DIR/.claude/hooks/no-os-scheduling.sh',
            'PreToolUse: ./scripts/my-guard.sh',
        ]);
        expect(result.removedHooks).toEqual([
            'settings.local.json PreToolUse: bash .claude/hooks/enforce-pre-tool.sh',
            'settings.local.json PreToolUse: bash $CLAUDE_PROJECT_DIR/.claude/hooks/protect-task-scaffolding.sh',
            'settings.local.json SessionStart: bash .claude/hooks/resume-from-handoff.sh',
        ]);
    });

    it('leaves settings.local.json byte-identical when it has nothing of ours', async () => {
        const local = getClaudeLocalSettingsPath(root);
        await fs.mkdir(path.dirname(local), { recursive: true });
        const original = '{"permissions":{"allow":["Bash(ls:*)"]},"hooks":{"Stop":[]}}';
        await fs.writeFile(local, original);
        await applyClaudeSettings(root, {});
        expect(await fs.readFile(local, 'utf-8')).toBe(original);
    });

    it('re-applying is a no-op that reports nothing removed', async () => {
        await settingsWith(getClaudeSettingsPath(root), {
            PostToolUse: [cmd('bash .claude/hooks/check-context-and-handoff.sh')],
        });
        await applyClaudeSettings(root, { taskScaffoldingGuard: true });
        const second = await applyClaudeSettings(root, { taskScaffoldingGuard: true });
        expect(second.changed).toBe(false);
        expect(second.removedHooks).toEqual([]);
    });

    it('identifies rulebook hooks by whole script name only', () => {
        expect(isRulebookHook('bash .claude/hooks/terse-activate.sh')).toBe(true);
        expect(isRulebookHook('bash $CLAUDE_PROJECT_DIR/.claude/hooks/jev-gate.sh tool')).toBe(
            true
        );
        expect(isRulebookHook('bash .claude/hooks/my-terse-activate.sh')).toBe(false);
        expect(isRulebookHook('bash .claude/hooks/block-destructive-git.sh')).toBe(false);
    });
});
